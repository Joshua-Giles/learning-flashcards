/** Mirrors schema/set.schema.json — keep the two in sync. */
export interface Card {
  /** Unique within its set. Never renamed or reused: progress is keyed on `setId/cardId`. */
  id: string;
  prompt: string;
  /** Short, typeable answer shown on the back of the card and used by the quiz. */
  answer: string;
  /** Alternative answers also accepted in the quiz. */
  accept?: string[];
  /** Fun, informative context. Light markdown: **bold**, *italic*, [links](https://…). */
  details?: string;
  hint?: string;
  tags?: string[];
  /** Defaults to true. False excludes the card from typed quizzes. */
  quizzable?: boolean;
}

export interface CardSet {
  schemaVersion: 1;
  id: string;
  title: string;
  description: string;
  category: string;
  emoji: string;
  tags: string[];
  version: number;
  /** YYYY-MM-DD */
  updated: string;
  cards: Card[];
}

/** One entry of public/sets/index.json (generated by `npm run sets:check`). */
export interface SetSummary {
  id: string;
  title: string;
  description: string;
  category: string;
  emoji: string;
  tags: string[];
  version: number;
  updated: string;
  cardCount: number;
  quizzableCount: number;
}

export interface SetManifest {
  sets: SetSummary[];
}

export interface SetCategory {
  name: string;
  sets: SetSummary[];
}
